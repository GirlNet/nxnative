#!/usr/bin/env python3
"""Embed bcdec's BC7 decoder as Metal source for the runtime upload kernel.

The decoder and partition tables come from the vendored bcdec 0.985, under
its Unlicense option (dm/third_party/bcdec/LICENSE). Only address spaces,
integer types and initialization differ from the CPU reference.
Run this script after updating bcdec; --check verifies the committed output.
"""
import argparse
import json
import re
from pathlib import Path


def function(source, signature):
    start = source.index(signature)
    body = source.index("{", start)
    depth = 1
    end = body + 1
    while depth:
        depth += (source[end] == "{") - (source[end] == "}")
        end += 1
    return source[start:end]


def generate(source):
    decoder = function(source, "BCDECDEF void bcdec_bc7(const void* compressedBlock, void* decompressedBlock, int destinationPitch) {")
    decoder = re.sub(r"/\*.*?\*/", "", decoder, flags=re.S)
    tables = []
    for match in re.finditer(r"    static [^;]+;", decoder):
        tables.append(match.group().strip().replace("static ", "constant ", 1))
    assert len(tables) == 6, "bcdec BC7 tables changed; review the Metal adaptation"
    decoder = re.sub(r"    static [^;]+;", "", decoder)
    decoder = decoder.replace("BCDECDEF void bcdec_bc7(const void* compressedBlock, void* decompressedBlock, int destinationPitch)",
                              "void bcd7_decode(device const uchar* compressedBlock, thread uchar* decompressedBlock, int destinationPitch)")
    decoder = decoder.replace("int endpoints[6][4];", "int endpoints[6][4] = {{0}};")
    decoder = decoder.replace("int* weights, * weights2;", "constant int* weights; constant int* weights2;")
    decoder = decoder.replace("unsigned char* decompressed;", "thread uchar* decompressed;")
    decoder = decoder.replace("(unsigned char*)decompressedBlock", "decompressedBlock")
    decoder = decoder.replace("(const unsigned char*)compressedBlock", "compressedBlock")
    decoder = decoder.replace("bcdec__", "bcd7_")
    decoder = decoder.replace("char indices", "uchar indices")
    tables = "\n".join(tables).replace("unsigned char", "uchar").replace("constant char", "constant uchar")
    helpers = """
struct bcd7_bitstream_t { ulong low, high; };
inline ulong bcd7_getu64le(device const uchar* p) {
    ulong v = 0;
    for (uint i = 0; i < 8; ++i) v |= ulong(p[i]) << (8 * i);
    return v;
}
inline int bcd7_bitstream_read_bits(thread bcd7_bitstream_t* s, int n) {
    ulong mask = (1ul << n) - 1ul;
    int v = int(s->low & mask);
    s->low = (s->low >> n) | ((s->high & mask) << (64 - n));
    s->high >>= n;
    return v;
}
inline int bcd7_bitstream_read_bit(thread bcd7_bitstream_t* s) {
    return bcd7_bitstream_read_bits(s, 1);
}
inline int bcd7_interpolate(int a, int b, constant int* weights, int index) {
    return (a * (64 - weights[index]) + b * weights[index] + 32) >> 6;
}
inline void bcd7_swap_values(thread int* a, thread int* b) {
    int t = *a; *a = *b; *b = t;
}
"""
    metal = "// BC7 decoder adapted from bcdec 0.985 (Unlicense).\n" + tables + "\n" + helpers + "\n" + decoder + "\n"
    metal = re.sub(r"\n[ \t]*\n(?:[ \t]*\n)+", "\n\n", metal)
    return ("// Generated by make_bc7_msl.py from dm/third_party/bcdec/bcdec.h.\n"
            "// Adapted under bcdec's Unlicense option; see dm/third_party/bcdec/LICENSE.\n"
            + "\n".join(json.dumps(line + "\n", ensure_ascii=True) for line in metal.splitlines()) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    here = Path(__file__).resolve().parent
    result = generate((here.parents[1] / "third_party/bcdec/bcdec.h").read_text(encoding="utf-8"))
    output = here / "nvn_bc7_msl.inc"
    if args.check:
        if output.read_text(encoding="utf-8") != result:
            raise SystemExit("BC7 Metal source is stale; run make_bc7_msl.py")
        print("BC7 Metal source matches the vendored decoder")
    else:
        output.write_text(result, encoding="utf-8", newline="\n")
        print(output)


if __name__ == "__main__":
    main()
